def get_axis_range_by_combo():
    """{(packet, band_str): (y_min, y_max)} -- ONE shared Y-axis span per
    (packet,band) slide (2026-08-15 customer request), computed from every
    real value shown on that slide: Bench (every offset), ATE (if any
    matched), and every offset's own spec Limit -- see
    make_bt_tx_acp_revision2.compute_shared_span's docstring for the full
    rationale. Supersedes both the 2026-07-19 fixed -50/-20 window this
    function used to return unconditionally, and the 2026-08-14 per-
    offset-adaptive design that briefly replaced it."""
    import bt_tx_acp_spec_lookup as spec_lookup
    import make_ate_tx_acp_revision2 as ate_acp_mod
    spec_table = spec_lookup.parse_spec(PATHS.bt_tx_spec_workbook or PATHS.spec_workbook)
    raw, pa_slices_seen, dig_gain_seen = ACP_CHART.read_all(PATHS.bench_dir)
    pa_slices_max = max(pa_slices_seen)
    dig_gain_max = max(dig_gain_seen)
    data = ACP_CHART.build_fixed_combos(raw, pa_slices_max, dig_gain_max)
    ate_idx = None
    if PATHS.extract_mode != "bench":
        try:
            ate_idx = ate_acp_mod.parse_ate_acp_records(ate_acp_mod.ATE_CSV)
        except (FileNotFoundError, OSError):
            ate_idx = None
    ranges = {}
    for combo, offset_map in data.items():
        packet, gain, band = combo
        specs = [spec_lookup.lookup(spec_table, packet, int(off)) for off in ACP_CHART.SLIDE_OFFSETS]
        extra_range = ate_acp_mod.get_ate_slide_extent(combo, offset_map, ate_idx)
        ranges[(packet, ACP_CHART.fmt_num(band))] = ACP_CHART.compute_shared_span(offset_map, extra_range, specs)
    return ranges


def get_offset_stats_by_combo():
    """offset_stats[(packet, band)][offset] = (mean, min, max, std), pooled
    across ALL frequencies for that offset -- the same population that
    offset's chart histograms, stacked by frequency color. Separate from
    get_axis_range_by_combo since the Y-axis itself stays fixed (no need to
    recompute it), but the stats table (2026-07-19, see
    share/PPT_FORMAT_STANDARD.md) needs real per-offset numbers."""
    raw, pa_slices_seen, dig_gain_seen = ACP_CHART.read_all(PATHS.bench_dir)
    pa_slices_max = max(pa_slices_seen)
    dig_gain_max = max(dig_gain_seen)
    data = ACP_CHART.build_fixed_combos(raw, pa_slices_max, dig_gain_max)
    offset_stats = {}
    for (packet, gain, band), offset_map in data.items():
        key = (packet, ACP_CHART.fmt_num(band))
        stats = {}
        for offset, freq_map in offset_map.items():
            pooled = [v for values in freq_map.values() for v in values]
            if pooled:
                stats[offset] = _stats(pooled)
        offset_stats[key] = stats
    return offset_stats

