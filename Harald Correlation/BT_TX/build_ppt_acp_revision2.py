def fmt_band(band: str) -> str:
    return f"{float(band):g}"


def discover(png_dir: Path):
    """Return data[(packet, band)][offset] = path."""
    data: dict = defaultdict(dict)
    for p in sorted(png_dir.glob("*.png")):
        m = FNAME_RE.match(p.name)
        if not m:
            print(f"  WARN: no match {p.name}")
            continue
        data[(m["packet"], m["band"])][int(m["offset"])] = p
    return data


def discover_legends(legend_dir: Path):
    """Return legends[(packet, band)] = path -- one standalone legend image
    per (packet,band) combo, shared across all 13 offset charts on that
    slide since they all use the same frequency/color set."""
    legends: dict = {}
    for p in sorted(legend_dir.glob("*.png")):
        m = LEGEND_FNAME_RE.match(p.name)
        if not m:
            print(f"  WARN: no match {p.name}")
            continue
        legends[(m["packet"], m["band"])] = p
    return legends


def _find_layout(prs, prefix, fallback):
    for i, layout in enumerate(prs.slide_layouts):
        if layout.name.startswith(prefix):
            return i
    return fallback


def _get_ph(slide, idx):
    for ph in slide.placeholders:
        if ph.placeholder_format.idx == idx:
            return ph
    return None


def _remove_placeholder(slide, idx: int) -> None:
    ph = _get_ph(slide, idx)
    if ph is not None:
        ph._element.getparent().remove(ph._element)


def _add_label(slide, left, top, width, height, text, size=10, bold=True, shrink_to_fit=False, wrap=True):
    box = slide.shapes.add_textbox(Inches(left), Inches(top), Inches(width), Inches(height))
    tf = box.text_frame
    tf.word_wrap = wrap
    tf.vertical_anchor = MSO_ANCHOR.MIDDLE
    tf.margin_left = 0
    tf.margin_right = 0
    tf.margin_top = 0
    tf.margin_bottom = 0
    if shrink_to_fit:
        tf.auto_size = MSO_AUTO_SIZE.TEXT_TO_FIT_SHAPE
    p = tf.paragraphs[0]
    p.alignment = PP_ALIGN.CENTER
    run = p.add_run()
    run.text = text
    run.font.size = Pt(size)
    run.font.bold = bold
    return box


def _add_ruler(slide, left, top, width, height, vmin: int, vmax: int, row_label=None):
    """row_label (2026-08-26): "Bench"/"ATE" text centered on this ruler --
    see build_ppt_pwr_evm_revision2.py's own _add_ruler docstring for why."""
    tick_h = 0.2
    _add_label(slide, left, top, width, tick_h, f"{vmax}", size=9, bold=True)
    _add_label(slide, left, top + height - tick_h, width, tick_h, f"{vmin}", size=9, bold=True)
    if row_label:
        # 2026-08-27: RULER_WIDTH widened to 0.9in (was 0.6in) so this can
        # stay a plain 16pt, matching Harald/Cal -- see RULER_WIDTH's own
        # comment and build_ppt_pwr_evm_revision2.py's _add_ruler
        # docstring for the two narrower-column workarounds this replaces.
        label_h = 0.4
        label_top = top + (height - label_h) / 2
        _add_label(slide, left, label_top, width, label_h, row_label, size=16, bold=True)


def _add_image_stretched(slide, path: Path, cell_left, cell_top, cell_width, cell_height):
    slide.shapes.add_picture(
        str(path), Inches(cell_left), Inches(cell_top), Inches(cell_width), Inches(cell_height)
    )


def _stats(values):
    """(mean, min, max, std) -- std is 0.0 for a single-point sample."""
    return (statistics.mean(values), min(values), max(values),
            statistics.stdev(values) if len(values) > 1 else 0.0)


def _set_cell(cell, text, size=6, bold=True, color=None):
    """A truly empty string (blank USL/LSL cell) makes PowerPoint render
    that ROW much taller than TABLE_ROW_H -- confirmed via win32com
    (11.52pt baseline vs 23.6pt with one empty cell): a run with no
    characters has nothing to measure, so PowerPoint falls back to a much
    larger default line height for that row instead of the 6pt we set on
    the (now-empty) run. A single space keeps the cell visually blank but
    gives PowerPoint an actual 6pt glyph to size the row against."""
    cell.vertical_anchor = MSO_ANCHOR.MIDDLE
    cell.margin_left = Pt(2)
    cell.margin_right = Pt(2)
    cell.margin_top = Pt(1)
    cell.margin_bottom = Pt(1)
    tf = cell.text_frame
    tf.word_wrap = True
    tf.text = text if text else " "
    for p in tf.paragraphs:
        p.alignment = PP_ALIGN.CENTER
        run = p.runs[0] if p.runs else p.add_run()
        run.font.size = Pt(size)
        run.font.bold = bold
        if color is not None:
            run.font.color.rgb = color


def _grid_col_widths(cell_width, n_cols, gap=CELL_GAP_H):
    """Data-column widths for the stats table so each column's LEFT edge
    lines up with its corresponding chart image below it. The image grid
    has a `gap` gap between images (cell_left advances by cell_width+gap
    each column); a plain pptx table has no such inter-column gap, so
    without this every column after the first drifts left of its image by
    an accumulating amount (up to 11*CELL_GAP_H =~ 0.33in by ACP's last
    column). Widening every column but the last by `gap` reproduces that
    same per-column advance; the last column stays at the plain
    cell_width so the table's total width still matches the grid's total
    width exactly (n*cell_width + (n-1)*gap)."""
    if n_cols <= 1:
        return [cell_width] * n_cols
    return [cell_width + gap] * (n_cols - 1) + [cell_width]


def _add_stats_table(slide, left, col_widths, top, header_label, headers, data_rows, colvar_rows=None,
                      row_h=None):
    """Stats table under the title, columns aligned with the chart grid
    below it. data_rows: [(row_label, [value_str,...])]. colvar_rows:
    [(row_label, [value_str,...], color)] -- like data_rows but bold+colored,
    one cell per column, NOT merged -- ACP's USL genuinely differs by offset
    within one slide (e.g. 1DH5: -20dBm at +/-2, -37dBm at +/-3..5), so
    unlike a truly-constant spec it can't be merged into a single cell (see
    share/PPT_FORMAT_STANDARD.md and this project's 2026-07-19
    clarification beyond that doc). row_h (2026-07-20, optional): per-row
    height in inches, default TABLE_ROW_H -- lets the ATE table (always
    header+2 rows) stretch to match a taller Bench table's total height
    when the two sit side by side. Returns the table's total height in
    inches."""
    colvar_rows = colvar_rows or []
    row_h = row_h if row_h is not None else TABLE_ROW_H
    n_cols = 1 + len(headers)
    n_rows = 1 + len(data_rows) + len(colvar_rows)
    total_width = sum(col_widths)
    total_height = row_h * n_rows

    gframe = slide.shapes.add_table(n_rows, n_cols, Inches(left), Inches(top),
                                     Inches(total_width), Inches(total_height))
    table = gframe.table
    table.first_row = False
    for i, w in enumerate(col_widths):
        table.columns[i].width = Inches(w)
    for r in range(n_rows):
        table.rows[r].height = Inches(row_h)

    _set_cell(table.cell(0, 0), header_label, size=6)
    for ci, h in enumerate(headers, start=1):
        _set_cell(table.cell(0, ci), h, size=6)

    row_i = 1
    for label, values in data_rows:
        _set_cell(table.cell(row_i, 0), label, size=6)
        for ci, v in enumerate(values, start=1):
            _set_cell(table.cell(row_i, ci), v, size=6, bold=True)
        row_i += 1

    for label, values, color in colvar_rows:
        _set_cell(table.cell(row_i, 0), label, size=6, color=color)
        for ci, v in enumerate(values, start=1):
            _set_cell(table.cell(row_i, ci), v, size=6, bold=True, color=color)
        row_i += 1

    return total_height


ATE_BORDER_COLOR = RGBColor(0xC0, 0x00, 0x00)
