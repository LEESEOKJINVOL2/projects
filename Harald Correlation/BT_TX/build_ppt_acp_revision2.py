def _add_ate_placeholder(slide, left, top, width, height):
    """Empty bordered box labeled "ATE Data location" -- reserved space for
    ATE data to be added later (hard customer requirement)."""
    box = slide.shapes.add_textbox(Inches(left), Inches(top), Inches(width), Inches(height))
    box.line.color.rgb = ATE_BORDER_COLOR
    box.line.width = Pt(1.5)
    box.fill.background()
    tf = box.text_frame
    tf.word_wrap = True
    tf.margin_left = Pt(6)
    tf.margin_top = Pt(4)
    p = tf.paragraphs[0]
    p.alignment = PP_ALIGN.LEFT
    run = p.add_run()
    run.text = "ATE Data location"
    run.font.size = Pt(16)
    run.font.bold = True
    run.font.color.rgb = ATE_TEXT_COLOR
    return box


def _add_no_ate_box(slide, left, top, width, height):
    """Small per-column 'hole' for an offset with no ATE match (2026-07-20)
    -- unlike _add_ate_placeholder (one box spanning the whole row), this
    only covers ONE offset's cell so the other matched offsets on the same
    slide still show their ATE chart."""
    box = slide.shapes.add_shape(MSO_SHAPE.RECTANGLE, Inches(left), Inches(top), Inches(width), Inches(height))
    box.fill.background()
    box.line.color.rgb = ATE_BORDER_COLOR
    box.line.width = Pt(1)
    tf = box.text_frame
    tf.word_wrap = True
    tf.vertical_anchor = MSO_ANCHOR.MIDDLE
    p = tf.paragraphs[0]
    p.alignment = PP_ALIGN.CENTER
    run = p.add_run()
    run.text = "No ATE match"
    run.font.size = Pt(8)
    run.font.bold = True
    run.font.color.rgb = ATE_TEXT_COLOR


def _add_interleaved_table(slide, left, top, table_width, header_label, cond_labels,
                            bench_data_rows, ate_lookup, spec_rows=None):
    """ACP counterpart of build_ppt_pwr_evm_revision2._add_interleaved_table
    -- ONE combined table with Bench/ATE columns ALTERNATING per offset
    (2026-07-20 customer request: "Table이 Bench랑 ATE랑 번갈아가면서
    나오도록"). See that module's docstring for the full column-merging
    rationale. Returns the table's total height in inches."""
    spec_rows = spec_rows or []
    n_cond = len(cond_labels)
    n_data_cols = 2 * n_cond
    n_cols = 1 + n_data_cols
    n_rows = 2 + len(bench_data_rows) + len(spec_rows)

    grid_width = table_width - RULER_WIDTH
    cell_width = (grid_width - (n_data_cols - 1) * CELL_GAP_H) / n_data_cols
    col_widths = [RULER_WIDTH] + _grid_col_widths(cell_width, n_data_cols)
    total_width = sum(col_widths)
    total_height = TABLE_ROW_H * n_rows

    gframe = slide.shapes.add_table(n_rows, n_cols, Inches(left), Inches(top),
                                     Inches(total_width), Inches(total_height))
    table = gframe.table
    table.first_row = False
    for i, w in enumerate(col_widths):
        table.columns[i].width = Inches(w)
    for r in range(n_rows):
        table.rows[r].height = Inches(TABLE_ROW_H)

    _set_cell(table.cell(0, 0), header_label, size=6)
    _set_cell(table.cell(1, 0), "", size=6)
    for ci, label in enumerate(cond_labels):
        c1 = 1 + ci * 2
        merged = table.cell(0, c1)
        merged.merge(table.cell(0, c1 + 1))
        _set_cell(merged, label, size=6)
        _set_cell(table.cell(1, c1), "Bench", size=6)
        _set_cell(table.cell(1, c1 + 1), "ATE", size=6)

    row_i = 2
    for label, bench_vals in bench_data_rows:
        _set_cell(table.cell(row_i, 0), label, size=6)
        for ci in range(n_cond):
            c1 = 1 + ci * 2
            _set_cell(table.cell(row_i, c1), bench_vals[ci], size=6, bold=True)
            _set_cell(table.cell(row_i, c1 + 1), ate_lookup(label, ci), size=6, bold=True)
        row_i += 1

    for label, values, color in spec_rows:
        _set_cell(table.cell(row_i, 0), label, size=6, color=color)
        for ci in range(n_cond):
            c1 = 1 + ci * 2
            merged = table.cell(row_i, c1)
            merged.merge(table.cell(row_i, c1 + 1))
            _set_cell(merged, values[ci], size=6, bold=True, color=color)
        row_i += 1

    return total_height


def _add_ate_images(slide, usable_left, cell_width, top, height, present, ate_data):
    """Per offset column: the ATE chart image (matched) or a small
    _add_no_ate_box (not matched). present: [(offset, bench_path), ...]."""
    for ci, (off, _path) in enumerate(present):
        cell_left = usable_left + RULER_WIDTH + ci * (cell_width + CELL_GAP_H)
        info = ate_data.get(off)
        png = info["png"] if info else None
        if png is not None:
            _add_image_stretched(slide, png, cell_left, top, cell_width, height)
        else:
            _add_no_ate_box(slide, cell_left, top, cell_width, height)


def add_acp_slide(prs, layout_idx, title_text, offset_map, offset_stats, legend_path=None,
                   y_min=FIXED_Y_MIN_DEFAULT, y_max=FIXED_Y_MAX_DEFAULT, get_spec=None, ate_data=None):
    """Single row: offsets -6..6 (excluding 0) in order, ruler at the left
    (Min/Max only), one extra rightmost cell -- the same width/height as
    every offset cell -- holding the combo's standalone legend image.
    Stats table (Mean/Min/Max/Std per offset, plus a per-column USL row if
    get_spec is given) sits under the title; ATE placeholder box fills the
    reserved bottom half (or, when ate_data is given -- {offset: {"png":..,
    "stats":..} or None} -- an interleaved Bench/ATE table + a two-row
    Bench/ATE chart grid, 2026-07-20, see _add_interleaved_table)."""
    slide = prs.slides.add_slide(prs.slide_layouts[layout_idx])
    ph_title = _get_ph(slide, 1) or _get_ph(slide, 0)
    if ph_title:
        ph_title.text = title_text
    _remove_placeholder(slide, 12)

    present = [(off, offset_map[off]) for off in OFFSETS if off in offset_map]
    n_cols = len(present) + (1 if legend_path is not None else 0)

    usable_left = LEFT_MARGIN
    usable_right = SLIDE_WIDTH_IN - RIGHT_MARGIN
    grid_width = usable_right - usable_left - RULER_WIDTH
    cell_width = (grid_width - (n_cols - 1) * CELL_GAP_H) / n_cols

    headers = [f"{off}" for off, _path in present]
    mean_std, min_max = [], []
    for off, _path in present:
        s = offset_stats.get(off)
        if s:
            mean_std.append(f"{s[0]:.2f}±{s[3]:.2f}")
            min_max.append(f"{s[1]:.2f} / {s[2]:.2f}")
        else:
            mean_std.append(""); min_max.append("")
    data_rows = [("Mean±Std", mean_std), ("Min/Max", min_max)]

    colvar_rows = []
    if get_spec is not None:
        usl_vals, lsl_vals = [], []
        any_usl = any_lsl = False
        for off, _path in present:
            spec = get_spec(off)
            lsl, usl = spec if spec else (None, None)
            usl_vals.append(f"{usl:g}" if usl is not None else "")
            lsl_vals.append(f"{lsl:g}" if lsl is not None else "")
            any_usl = any_usl or usl is not None
            any_lsl = any_lsl or lsl is not None
        if any_usl:
            colvar_rows.append(("USL", usl_vals, USL_COLOR))
        if any_lsl:
            colvar_rows.append(("LSL", lsl_vals, USL_COLOR))

    if ate_data is not None:
        # 2026-07-20 customer request: ONE combined table with Bench/ATE
        # columns ALTERNATING per offset ("Table이 Bench랑 ATE랑 번갈아가면서
        # 나오도록") -- see _add_interleaved_table's docstring. Chart grid
        # below is unaffected (still the original two full-width stacked
        # rows, Bench row on top / ATE row + legend below).
        def ate_lookup(label, ci, _present=present):
            off, _path = _present[ci]
            info = ate_data.get(off)
            stats = info["stats"] if info else None
            if not stats:
                return ""
            return f"{stats[0]:.2f}±{stats[3]:.2f}" if label == "Mean±Std" else f"{stats[1]:.2f} / {stats[2]:.2f}"

        table_h = _add_interleaved_table(slide, usable_left, TABLE_TOP, usable_right - usable_left,
                                          "Offset", headers, data_rows, ate_lookup, spec_rows=colvar_rows)
    else:
        col_widths = [RULER_WIDTH] + _grid_col_widths(cell_width, len(present))
        table_h = _add_stats_table(slide, usable_left, col_widths, TABLE_TOP, "Offset", headers,
                                    data_rows, colvar_rows=colvar_rows)

    if ate_data is not None:
        # Plot stays the ORIGINAL two full-width stacked rows (Bench row on
        # top, ATE row + legend below) -- 2026-07-20 confirmed final: only
        # the table moves side by side, never the chart grid.
        plots_top = TABLE_TOP + table_h + TABLE_PLOT_GAP
        plots_bottom = CONTENT_AREA_BOTTOM
        bench_image_h = (plots_bottom - plots_top - ATE_GAP) / 2
        bench_image_top = plots_top
        ate_image_top = bench_image_top + bench_image_h + ATE_GAP
        ate_image_h = plots_bottom - ate_image_top

        # 2026-08-15 (customer request): axis is one shared span for the
        # WHOLE slide again (see make_bt_tx_acp_revision2.
        # compute_shared_span), so the left-of-row Min/Max ruler is
        # accurate again -- restored (was dropped 2026-08-14 during the
        # brief per-offset-adaptive design).
        _add_ruler(slide, usable_left, bench_image_top, RULER_WIDTH, bench_image_h, y_min, y_max, row_label="Bench")
        for ci, (off, path) in enumerate(present):
            cell_left = usable_left + RULER_WIDTH + ci * (cell_width + CELL_GAP_H)
            _add_image_stretched(slide, path, cell_left, bench_image_top, cell_width, bench_image_h)

        if legend_path is not None:
            legend_left = usable_left + RULER_WIDTH + len(present) * (cell_width + CELL_GAP_H)
            pic = slide.shapes.add_picture(str(legend_path), Inches(legend_left), Inches(bench_image_top),
                                            width=Inches(cell_width))
            legend_h_in = pic.height / 914400
            if legend_h_in > bench_image_h:
                pic.height = Inches(bench_image_h)
                pic.width = int(pic.height * pic.image.size[0] / pic.image.size[1])
            pic.top = Inches(bench_image_top)

        _add_ruler(slide, usable_left, ate_image_top, RULER_WIDTH, ate_image_h, y_min, y_max, row_label="ATE")
        _add_ate_images(slide, usable_left, cell_width, ate_image_top, ate_image_h, present, ate_data)
    else:
        content_top = TABLE_TOP + table_h + TABLE_GRID_GAP
        content_bottom = GRID_CONTENT_BOTTOM
        image_h = content_bottom - content_top

        _add_ruler(slide, usable_left, content_top, RULER_WIDTH, image_h, y_min, y_max)

        for ci, (off, path) in enumerate(present):
            cell_left = usable_left + RULER_WIDTH + ci * (cell_width + CELL_GAP_H)
            _add_image_stretched(slide, path, cell_left, content_top, cell_width, image_h)

        if legend_path is not None:
            legend_left = usable_left + RULER_WIDTH + len(present) * (cell_width + CELL_GAP_H)
            # Match cell WIDTH only -- forcing the height too (like the offset
            # charts) stretched the legend vertically and distorted the text.
            pic = slide.shapes.add_picture(str(legend_path), Inches(legend_left), Inches(content_top),
                                            width=Inches(cell_width))
            legend_h_in = pic.height / 914400
            if legend_h_in > image_h:
                pic.height = Inches(image_h)
                pic.width = int(pic.height * pic.image.size[0] / pic.image.size[1])
            pic.top = Inches(content_top)

        _add_ate_placeholder(slide, usable_left, GRID_CONTENT_BOTTOM + ATE_GAP,
                              usable_right - usable_left, CONTENT_AREA_BOTTOM - (GRID_CONTENT_BOTTOM + ATE_GAP))

    return slide


def main() -> None:
    prs = Presentation(TEMPLATE_PATH)
    content_layout_idx = _find_layout(prs, "1_", 5)

    print("Discovering ACP PNGs...")
    data = discover(ACP_PNG_DIR)
    print(f"  {len(data)} (packet, band) groups")
    legends = discover_legends(ACP_LEGEND_DIR)
    print(f"  {len(legends)} legend images")
    print("Computing per-combo Y-axis range...")
    axis_range_by_combo = get_axis_range_by_combo()
    print("Computing per-offset stats...")
    offset_stats_by_combo = get_offset_stats_by_combo()

    print("Parsing ACP spec limits...")
    import bt_tx_acp_spec_lookup as spec_lookup
    spec_table = spec_lookup.parse_spec(PATHS.bt_tx_spec_workbook or PATHS.spec_workbook)

    for packet, band in sorted(data.keys()):
        # 2026-08-27 (customer request via LEE SeokJin): every slide title
        # must show its HPA voltage. ACP only ever uses ONE fixed supply
        # (FIXED_SUPPLY -- see this module's own docstring), so unlike
        # Power/DEVM/FreqAcc/BW's Band2.4G there's no combine-vs-split
        # question here -- just always append it.
        title = f"BT_TX_ACP_{packet}_{fmt_band(band)}G_HPA_{pwr_mod.hpa_label(ACP_CHART.FIXED_SUPPLY)}"
        y_min, y_max = axis_range_by_combo.get((packet, band), (FIXED_Y_MIN_DEFAULT, FIXED_Y_MAX_DEFAULT))
        offset_stats = offset_stats_by_combo.get((packet, band), {})

        def get_spec(off, _packet=packet):
            return spec_lookup.lookup(spec_table, _packet, int(off))

        add_acp_slide(prs, content_layout_idx, title, data[(packet, band)], offset_stats,
                      legend_path=legends.get((packet, band)), y_min=y_min, y_max=y_max, get_spec=get_spec)

    report_dir = PATHS.report_dir
    report_dir.mkdir(parents=True, exist_ok=True)
    out_path = report_dir / f"{datetime.date.today().isoformat()}_BT_TX_ACP_Revision2.pptx"
    prs.save(out_path)
    print(f"Saved: {out_path}")


if __name__ == "__main__":
    main()
